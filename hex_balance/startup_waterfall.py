#!/usr/bin/env python3
"""Measures the time from launching the game until an AI match is running and prints it as a waterfall.

The game writes a time mark for each loading step if COW_PERF_TRACE is set (see coreengine/perftrace.h).
This script starts the game with an automation script, waits for the second turn of the match and
shows how long each step took. Several runs are averaged.

  python hex_balance/startup_waterfall.py                       normal window, 3 runs
  python hex_balance/startup_waterfall.py --no-ui --runs 5       headless
  python hex_balance/startup_waterfall.py --map "4_player/Hex Quad" --players 4
"""
import argparse
import json
import os
import subprocess
import sys
import time
from collections import OrderedDict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD_EXE = os.path.join(REPO, "build", "Commander_Wars.exe")
# the game expects its executable next to the maps and resources folders, so the build is copied to the game folder
EXE = os.path.join(REPO, "Commander_Wars.exe")


def update_exe():
    """copies a newer build next to the game data. Fails silently while the game is running."""
    try:
        if os.path.exists(BUILD_EXE) and (not os.path.exists(EXE) or os.path.getmtime(BUILD_EXE) > os.path.getmtime(EXE)):
            import shutil
            shutil.copy2(BUILD_EXE, EXE)
    except OSError:
        pass

QT_BIN = r"C:\msys64\mingw64\bin"
MAPS = REPO.replace("\\", "/") + "/maps/"

INIT = """// generated by hex_balance/startup_waterfall.py
var Init =
{
    main : function(menu)
    {
        // only start a match once. Coming back to the main menu after a match stays there.
        if (typeof hexAutomationStarted !== "undefined")
        {
            return;
        }
        hexAutomationStarted = true;
        menu.enterSingleplayer([]);
    },
    mapsSelection : function(menu)
    {
        // opening the map selection by hand later on shows the normal selection
        if (typeof hexAutomationMatchStarted !== "undefined")
        {
            return;
        }
        hexAutomationMatchStarted = true;
        var config = %s;
        menu.selectMap(config.folder, config.map);
        menu.buttonNext();
        menu.buttonNext();
        var selection = menu.getPlayerSelection();
        for (var i = 0; i < config.players; i++)
        {
            selection.selectPlayerAi(i, 2);
        }
        menu.startGame();
    },
}
"""


def kill_tree(pid):
    subprocess.run(["taskkill", "/F", "/T", "/PID", str(pid)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def run_once(args, index):
    user_dir = os.path.join(REPO, "build", "balance", "perf")
    os.makedirs(user_dir, exist_ok=True)
    folder, map_name = args.map.replace("\\", "/").rsplit("/", 1)
    with open(os.path.join(user_dir, "init.js"), "w", encoding="utf-8") as handle:
        handle.write(INIT % json.dumps({"folder": MAPS + folder + "/", "map": map_name + ".map", "players": args.players}))
    settings_file = os.path.join(REPO, "Commander_Wars.ini")
    if os.path.exists(settings_file):
        with open(settings_file, "r", encoding="utf-8", errors="replace") as handle:
            lines = handle.read().splitlines()
        lines = ["UserPath=" + user_dir.replace("\\", "/") + "/" if line.startswith("UserPath=") else line for line in lines]
        with open(os.path.join(user_dir, "Commander_Wars.ini"), "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")
    trace = os.path.join(user_dir, "trace_%d.txt" % index)
    if os.path.exists(trace):
        os.remove(trace)
    env = dict(os.environ)
    env["PATH"] = QT_BIN + os.pathsep + env.get("PATH", "")
    # the game waits this long in each menu before it calls the automation script (10 seconds without it)
    env["COW_MENU_ENTER_DELAY_MS"] = str(args.menu_delay)
    env["COW_PERF_TRACE"] = trace
    command = [EXE, "--userPath", user_dir.replace("\\", "/") + "/"]
    if args.no_ui:
        command.append("--noUi")
    launch = int(time.time() * 1000)
    process = subprocess.Popen(command, cwd=REPO, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    marks = []
    try:
        deadline = time.time() + args.timeout
        while time.time() < deadline and process.poll() is None:
            time.sleep(0.25)
            marks = read_marks(trace, process.pid)
            if sum(1 for _, name in marks if name == "turn") >= 2:
                break
    finally:
        kill_tree(process.pid)
        process.wait()
    return [(stamp - launch, name) for stamp, name in marks]


def read_marks(trace, pid):
    marks = []
    if os.path.exists(trace):
        with open(trace, "r", encoding="utf-8", errors="replace") as handle:
            for line in handle:
                parts = line.rstrip("\n").split(";", 2)
                # the ai helper process writes into the same file
                if len(parts) == 3 and parts[0].isdigit() and parts[1] == str(pid):
                    marks.append((int(parts[0]), parts[2]))
    return marks


def segments(marks):
    """A segment lasts from its mark to the next mark. Repeated names get a counter."""
    result = OrderedDict()
    counts = {}
    result["process start (before main)"] = (0, marks[0][0] if marks else 0)
    for i, (stamp, name) in enumerate(marks[:-1]):
        counts[name] = counts.get(name, 0) + 1
        key = name if counts[name] == 1 else "%s #%d" % (name, counts[name])
        result[key] = (stamp, marks[i + 1][0] - stamp)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--map", default="2_player/Hex River")
    parser.add_argument("--players", type=int, default=2)
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--no-ui", action="store_true", help="measure the headless mode used for the balance batches")
    parser.add_argument("--menu-delay", type=int, default=250, help="ms the game waits in each menu before the automation continues. The game default is 10000")
    parser.add_argument("--timeout", type=int, default=240)
    parser.add_argument("--min-ms", type=int, default=100, help="steps shorter than this are summed up as 'other'")
    args = parser.parse_args()
    update_exe()
    if not os.path.exists(EXE):
        sys.exit("missing " + EXE)

    runs = []
    for index in range(args.runs):
        marks = run_once(args, index)
        if sum(1 for _, name in marks if name == "turn") < 2:
            print("run %d: the match was not reached (%d marks)" % (index, len(marks)))
            continue
        runs.append(segments(marks))
        print("run %d: %.1f s until the second turn" % (index, marks[-1][0] / 1000.0))
    if not runs:
        sys.exit("no complete run")

    # average the steps over the runs, keeping the order of the first run
    names = list(runs[0].keys())
    rows = []
    for name in names:
        values = [run[name] for run in runs if name in run]
        start = sum(v[0] for v in values) / len(values)
        duration = sum(v[1] for v in values) / len(values)
        rows.append((name, start, duration))
    total = max(start + duration for _, start, duration in rows)
    width = 50
    print("\n%s, %d run(s), %s. Total %.1f s until the second turn.\n" % (
        args.map, len(runs), "headless" if args.no_ui else "with window", total / 1000.0))
    print("%-46s %8s %8s  %s" % ("step", "start s", "took s", "waterfall"))
    other = 0.0
    for name, start, duration in rows:
        if duration < args.min_ms:
            other += duration
            continue
        left = int(round(start / total * width))
        bar = max(1, int(round(duration / total * width)))
        print("%-46s %8.2f %8.2f  %s%s" % (name[:46], start / 1000.0, duration / 1000.0, " " * left, "#" * bar))
    print("%-46s %8s %8.2f" % ("other (steps below %d ms)" % args.min_ms, "", other / 1000.0))
    print("\nlargest steps:")
    for name, start, duration in sorted(rows, key=lambda row: -row[2])[:8]:
        print("  %5.1f s  %4.1f%%  %s" % (duration / 1000.0, 100.0 * duration / total, name))


if __name__ == "__main__":
    main()
