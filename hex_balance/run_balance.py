#!/usr/bin/env python3
"""Runs headless AI only matches of the hex grid prototype and collects the results.

Each match starts the locally built game with its own user path and an init.js which selects the map,
the AI's and CO's, adds a day limit and prints the result when the victory screen is reached.

Examples (run from anywhere):
  python hex_balance/run_balance.py --map "2_player/Hex River" --cos CO_ANDY CO_MAX --games 10
  python hex_balance/run_balance.py --map "3_player/Hex Triad" --cos CO_ANDY CO_MAX CO_SAMI --games 12
  python hex_balance/run_balance.py --map "4_player/Hex Quad" --cos CO_ANDY CO_MAX CO_SAMI CO_GRIT --games 8 --jobs 4
  python hex_balance/run_balance.py --map "2_player/Hex River" --cos CO_ANDY CO_MAX --games 10 --square
  python hex_balance/run_balance.py --map "4_player/Hex Quad" --cos CO_ANDY CO_MAX CO_SAMI CO_GRIT --watch
  python hex_balance/run_balance.py --map "4_player/Hex Quad" --cos CO_ANDY CO_MAX CO_SAMI CO_GRIT --watch --speed max
  python hex_balance/run_balance.py --map "3_player/Hex Triad" --cos CO_ANDY CO_MAX CO_SAMI --watch --simultaneous --human 1 --speed normal

The CO's are rotated through the seats from game to game, so every CO plays every seat equally often
if the number of games is a multiple of the player count.
"""
