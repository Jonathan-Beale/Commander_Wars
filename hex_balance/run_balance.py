LIMIT_RULES = {"capture": "VICTORYRULE_TURNLIMIT_CAPTURE_RACE", "score": "VICTORYRULE_TURNLIMIT_SCORE_RACE", "none": "VICTORYRULE_TURNLIMIT"}


def kill_tree(pid):
    subprocess.run(["taskkill", "/F", "/T", "/PID", str(pid)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def run_game(game, args, worker_dirs, lock):
    with lock:
        user_dir = worker_dirs.pop()
    try:
        os.makedirs(user_dir, exist_ok=True)
        folder, map_name = args.map.replace("\\", "/").rsplit("/", 1)
        config = {"folder": MAPS + folder + "/", "map": map_name + ".map",
                  "players": [{"co": co, "ai": args.ai} for co in game["cos"]],
                  "days": args.days, "limitRule": LIMIT_RULES[args.limit], "fog": args.fog, "simultaneous": args.simultaneous, "rules": args.rule}
        with open(os.path.join(user_dir, "init.js"), "w", encoding="utf-8") as handle:
            handle.write(INIT_TEMPLATE % {"config": json.dumps(config), "tag": RESULT_TAG, "speed": "normal"})
        env = dict(os.environ)
        env["PATH"] = QT_BIN + os.pathsep + env.get("PATH", "")
        # the game waits this long in each menu before it calls the automation script (10 seconds without it)
        env["COW_MENU_ENTER_DELAY_MS"] = str(args.menu_delay)
        env.pop("COW_SQUARE_GRID", None)
        if args.square:
            env["COW_SQUARE_GRID"] = "1"
        log_path = os.path.join(user_dir, "game_%03d.log" % game["index"])
        start = time.time()
        result = None
        with open(log_path, "w", encoding="utf-8", errors="replace") as log:
            process = subprocess.Popen([EXE, "--userPath", user_dir.replace("\\", "/") + "/", "--noUi", "--spawnAiProcess", "0"], cwd=REPO, env=env,
                                       stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True, errors="replace")
            timer = threading.Timer(args.timeout, kill_tree, [process.pid])
            timer.start()
            try:
                for line in process.stderr:
                    log.write(line)
                    if RESULT_TAG in line:
                        text = line.split(RESULT_TAG, 1)[1]
                        result = json.loads(text[:text.rindex("}") + 1])
                        break
            finally:
                timer.cancel()
                kill_tree(process.pid)
                process.wait()
        game["seconds"] = round(time.time() - start, 1)
        game["result"] = result
        return game
    finally:
        with lock:
            worker_dirs.append(user_dir)


