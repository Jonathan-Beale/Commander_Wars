def network(args, cos):
    """Hosts a network match or joins one. Each instance has its own user path, so two can run on one computer."""
    hosting = args.host
    name = args.instance or ("host" if hosting else "join")
    user_dir = os.path.join(REPO, "build", "balance", name)
    os.makedirs(user_dir, exist_ok=True)
    remote = [seat - 1 for seat in args.remote]
    human = [seat - 1 for seat in args.human]
    if hosting:
        folder, map_name = args.map.replace("\\", "/").rsplit("/", 1)
        rules = list(args.rule)
        if args.simultaneous:
            rules.append("GAMERULE_SIMULTANEOUS_TURNS")
        # 200 is an open seat for a player of another computer, 0 a human at this computer
        players = [{"co": co, "ai": 200 if seat in remote else (0 if seat in human else args.ai)} for seat, co in enumerate(cos)]
        config = {"host": True, "folder": MAPS + folder + "/", "map": map_name + ".map", "players": players, "days": args.days,
                  "limitRule": LIMIT_RULES[args.limit], "fog": args.fog, "rules": rules, "localSeats": human}
    else:
        config = {"host": False, "address": args.join, "localSeats": human}
    config["autoStart"] = not args.manual_start
    config["autoPlay"] = args.autoplay
    config["speed"] = args.speed
    settings_file = os.path.join(REPO, "Commander_Wars.ini")
    lines = []
    if os.path.exists(settings_file):
        with open(settings_file, "r", encoding="utf-8", errors="replace") as handle:
            lines = handle.read().splitlines()
    # each player of a match needs an own name. The user path of the settings file would replace the one of the command line
    username = args.username or name
    lines = ["UserPath=" + user_dir.replace("\\", "/") + "/" if line.startswith("UserPath=") else
             ("Username=" + username if line.startswith("Username=") else line) for line in lines]
    # A direct match needs no lobby server: without its address the game doesn't contact the public one and doesn't ask for a login
    # host and guests have to use the same port
    lines = ["GamePort=%d" % args.port if line.startswith("GamePort=") else line for line in lines]
    lines = ["ServerAdress=127.0.0.1" if line.startswith("ServerAdress=") else
             ("SecondaryServerAdress=" if line.startswith("SecondaryServerAdress=") else line) for line in lines]
    with open(os.path.join(user_dir, "Commander_Wars.ini"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    with open(os.path.join(user_dir, "init.js"), "w", encoding="utf-8") as handle:
        handle.write(NET_TEMPLATE % {"config": json.dumps(config), "tag": NET_TAG})
    env = dict(os.environ)
    env["PATH"] = QT_BIN + os.pathsep + env.get("PATH", "")
    env["COW_MENU_ENTER_DELAY_MS"] = str(max(args.menu_delay, 1500))
    env["COW_MENU_REENTER_MS"] = "1500"
    # The encrypted handshake of a direct match crashes the host with the Qt and OpenSSL versions of this build.
    # The host and all guests have to use the same setting.
    env["COW_PLAIN_TCP"] = "1"
    env.pop("COW_SQUARE_GRID", None)
    if hosting:
        print("hosting on port %d. The other players join the address of this computer (see ipconfig)." % args.port)
    else:
        print("joining " + args.join)
    # the ai of a network match runs inside of the game process of the host
    command = [EXE, "--userPath", user_dir.replace("\\", "/") + "/", "--spawnAiProcess", "0"]
    if os.environ.get("COW_NET_DEBUG"):
        # writes everything the game does to its console.log
        command += ["--debugLevel", "0"]
    subprocess.run(command, cwd=REPO, env=env)



def winner_of(result):
    """Returns the winning seat or -1 for a draw. Without a winner team the strongest remaining player wins."""
    if result is None:
        return None
    players = result["players"]
    if result["winnerTeam"] >= 0:
        seats = [i for i, player in enumerate(players) if player["team"] == result["winnerTeam"]]
        if len(seats) == 1:
            return seats[0]
    alive = [i for i, player in enumerate(players) if not player["defeated"]]
    if len(alive) == 1:
        return alive[0]
    candidates = alive if alive else list(range(len(players)))
    best = max(players[i]["strength"] for i in candidates)
    leaders = [i for i in candidates if players[i]["strength"] == best]
    return leaders[0] if len(leaders) == 1 else -1


